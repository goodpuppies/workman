export type SurfaceRuleCoverage = Readonly<{
  classified: number;
  missing: readonly string[];
  unknown: readonly string[];
  duplicates: readonly string[];
  missingBuilders: readonly string[];
  unknownConstructors: readonly string[];
}>;

export function surfaceRuleCoverage(grammar: WorkmanGrammarIr): SurfaceRuleCoverage {
  const grammarRules = new Set(grammar.rules.map((rule) => rule.name));
  const seen = new Set<string>();
  const duplicates: string[] = [];
  const unknown: string[] = [];
  for (const names of Object.values(surfaceRuleGroups)) {
    for (const name of names) {
      if (seen.has(name)) duplicates.push(name);
      seen.add(name);
      if (!grammarRules.has(name)) unknown.push(name);
    }
  }
  const nodeRules = new Set(surfaceRuleGroups.node);
  const constructorNames = new Set(
    constructors.map((constructor) => constructor.slice(0, constructor.indexOf("<"))),
  );
  const missingBuilders = [...nodeRules].filter((name) => !(name in surfaceBuilderPlan));
  const unknownConstructors = Object.values(surfaceBuilderPlan)
    .flatMap((names) => names)
    .filter((name) => !constructorNames.has(name));
  return Object.freeze({
    classified: seen.size,
    missing: Object.freeze([...grammarRules].filter((name) => !seen.has(name)).sort()),
    unknown: Object.freeze(unknown.sort()),
    duplicates: Object.freeze(duplicates.sort()),
    missingBuilders: Object.freeze(missingBuilders.sort()),
    unknownConstructors: Object.freeze([...new Set(unknownConstructors)].sort()),
  });
}

export function emitSurfaceTypes(grammar: WorkmanGrammarIr, grammarHash: string): string {
  return [
    "-- Generated by scripts/generate_frontend_v2_recognizer.ts. Do not edit.",
    `-- Grammar: ${grammar.sourcePath}`,
    `-- Grammar IR SHA-256: ${grammarHash}`,
    "-- Formatting-focused Surface AST. It does not reproduce Peggy semantic actions.",
    "",
    "record Span = {",
    "  start: Number,",
    "  end: Number,",
    "};",
    "",
    "record SurfaceComment = {",
    "  text: String,",
    "  span: Span,",
    "};",
    "",
    "record SurfaceToken = {",
    "  kind: String,",
    "  text: String,",
    "  span: Span,",
    "  leadingComments: List<SurfaceComment>,",
    "  recoveryId: Option<Number>,",
    "};",
    "",
    "type SurfaceValue<T> = AuthoredValue<T> | MarkedValue<Number, T>;",
    "type RepairClass = AutoFix | RecoveryOnly;",
    "",
    "record RecoveryMark = {",
    "  id: Number,",
    "  anchor: Number,",
    "  expectedText: String,",
    "  rule: String,",
    "  repairClass: RepairClass,",
    "};",
    "",
    "type SurfaceNode =",
    ...constructors.map((constructor, index) =>
      `  ${index === 0 ? "| " : "| "}${constructor}${index === constructors.length - 1 ? ";" : ""}`
    ),
    "",
    "record SurfaceProgram = {",
    "  root: SurfaceNode,",
    "  marks: List<RecoveryMark>,",
    "  preamble: String,",
    "};",
    "",
  ].join("\n");
}

export function emitSurfaceRuleMetadata(
  grammar: WorkmanGrammarIr,
  grammarHash: string,
): string {
  return [
    "-- Generated by scripts/generate_frontend_v2_recognizer.ts. Do not edit.",
    `-- Grammar: ${grammar.sourcePath}`,
    `-- Grammar IR SHA-256: ${grammarHash}`,
    "-- Mechanical rule classifications consumed by Surface construction.",
    "",
    emitRuleMatcher(
      "isTriviaRule",
      [...surfaceRuleGroups.trivia, ...surfaceRuleGroups.boundary],
    ),
    "",
    emitRuleMatcher("isTokenRule", surfaceRuleGroups.token),
    "",
    emitRuleMatcher("isListRule", surfaceRuleGroups.list),
    "",
    emitRuleMatcher("isTransparentRule", surfaceRuleGroups.transparent),
    "",
  ].join("\n");
}

function emitRuleMatcher(name: string, rules: readonly string[]): string {
  return [
    `let ${name} = match(name) => {`,
    ...rules.map((rule) => `  ${JSON.stringify(rule)} => { true },`),
    "  _ => { false },",
    "};",
  ].join("\n");
}

