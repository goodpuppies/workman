// `wm test`: finds `*.test.wm` files, writes one entry module that imports
// them all and hands their `tests` to testman's runner, and runs it like
// `wm run`. testman (tooling/testman) is a proposal for the shape of a Workman
// testing framework, not a settled design.
import { runFile } from "./run.ts";
import { fileURLToPath } from "node:url";
import { relative, resolve } from "node:path";

const runner = fileURLToPath(new URL("../tooling/testman/runner.wm", import.meta.url));

// Directories never searched for tests.
const skipped = new Set(["node_modules", ".git", ".build", "research", "_scratch"]);

async function collect(path: string, found: string[]): Promise<void> {
  const info = await Deno.stat(path);
  if (info.isFile) {
    if (path.endsWith(".test.wm")) found.push(path);
    return;
  }
  const entries = [];
  for await (const entry of Deno.readDir(path)) entries.push(entry);
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    if (entry.isDirectory && (skipped.has(entry.name) || entry.name.startsWith("."))) continue;
    if (entry.isDirectory || entry.name.endsWith(".test.wm")) await collect(`${path}/${entry.name}`, found);
  }
}

function usage(): number {
  console.error("usage: wm test [file.test.wm | dir]... [--filter text]");
  return 2;
}

export async function testCommand(args: string[]): Promise<number> {
  const paths: string[] = [];
  const passed: string[] = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--filter") {
      if (args[i + 1] === undefined) return usage();
      passed.push("--filter", args[++i]);
    } else if (args[i] === "--help" || args[i] === "-h") {
      return usage();
    } else {
      paths.push(args[i]);
    }
  }
  const files: string[] = [];
  for (const path of paths.length > 0 ? paths : ["."]) await collect(resolve(path), files);
  if (files.length === 0) {
    console.error("error: no test files (*.test.wm) found");
    return 1;
  }

  // wm imports are relative paths, so the entry module refers to everything
  // relative to the directory it is written in.
  const dir = await Deno.makeTempDir({ prefix: "wm-test-" });
  const from = (file: string) => {
    const path = relative(dir, file);
    return JSON.stringify(path.startsWith(".") ? path : `./${path}`);
  };
  const imports = files.map((file, index) => `from ${from(file)} import * as Suite${index};`);
  const suites = files.map((file, index) =>
    `Runner.suite(${JSON.stringify(relative(Deno.cwd(), file) || file)}, Suite${index}.tests)`
  );
  const entry = [
    "-- Generated by `wm test`.",
    `from ${from(runner)} import * as Runner;`,
    ...imports,
    `let main = () => { Runner.runSuites([${suites.join(", ")}]) };`,
    "",
  ].join("\n");

  try {
    const file = `${dir}/main.wm`;
    await Deno.writeTextFile(file, entry);
    const result = await runFile(file, { args: passed });
    return result.code;
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
}
