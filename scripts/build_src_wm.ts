// Compiles the repository's natively imported Workman modules into tracked library artifacts
// under src/generated/wm/, and maps each module to its artifact in deno.json's import map, so
// TypeScript imports `module.wm` directly: Deno runs the artifact, while tsc types the source
// through the content mapper.
//
// The modules are every `.wm` file under src/ (outside src/generated/), so a new module can be
// built before anything imports it, and every `.wm` module that TypeScript in src/, tests/,
// scripts/ or tooling/ imports with a literal specifier.
//
// A single run is one bootstrap stage. The compiler may itself import these modules, so
// `deno task generate` repeats the task until the artifacts stop changing.
import { compileLibraryFile } from "../src/compiler.ts";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(root, "src");
const generated = join(src, "generated");
const artifacts = join(generated, "wm");
const importers = ["src", "tests", "scripts", "tooling"].map((name) => join(root, name));

const modules = new Set<string>();
for await (const path of files(src)) if (path.endsWith(".wm")) modules.add(path);
for (const directory of importers) {
  for await (const path of files(directory)) {
    if (!/\.m?ts$/.test(path)) continue;
    for (const specifier of wmImports(await Deno.readTextFile(path))) {
      const module = resolve(dirname(path), specifier);
      if (specifier.startsWith(".") && await exists(module)) modules.add(module);
    }
  }
}

const imports: Record<string, string> = {};
const expected = new Set<string>();
for (const module of [...modules].sort()) {
  const name = relative(root, module);
  const artifact = join(artifacts, `${name}.js`);
  expected.add(artifact);
  imports[`./${name}`] = `./${relative(root, artifact)}`;
  const output = [
    `// Generated by scripts/build_src_wm.ts from ${name}. Do not edit by hand.`,
    await compileLibraryFile(module, { frontend: "v2" }),
  ].join("\n");
  await writeIfChanged(artifact, output);
}
await removeStale(artifacts);
await updateImportMap(imports);

/**
 * Literal `.wm` specifiers of TS import and export declarations (which start a line, unlike
 * Workman import syntax quoted in test sources) and of dynamic imports.
 */
function wmImports(text: string): string[] {
  const declarations = /^\s*(?:import|export)\b[^;]*?\bfrom\s*["']([^"']+\.wm)["']\s*;/gm;
  const dynamic = /\bimport\(\s*["']([^"']+\.wm)["']\s*\)/g;
  return [...text.matchAll(declarations), ...text.matchAll(dynamic)].map((match) => match[1]);
}

async function* files(directory: string): AsyncGenerator<string> {
  for await (const entry of Deno.readDir(directory)) {
    const path = join(directory, entry.name);
    if (entry.isDirectory && path !== generated && entry.name !== "node_modules") {
      yield* files(path);
    }
    if (entry.isFile) yield path;
  }
}

async function exists(path: string): Promise<boolean> {
  return await Deno.stat(path).then((info) => info.isFile, () => false);
}

async function writeIfChanged(path: string, text: string): Promise<void> {
  const current = await Deno.readTextFile(path).catch((error) => {
    if (error instanceof Deno.errors.NotFound) return undefined;
    throw error;
  });
  if (current === text) return;
  await Deno.mkdir(dirname(path), { recursive: true });
  await Deno.writeTextFile(path, text);
}

async function removeStale(directory: string): Promise<void> {
  const entries = await Array.fromAsync(Deno.readDir(directory)).catch((error) => {
    if (error instanceof Deno.errors.NotFound) return [];
    throw error;
  });
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory) {
      await removeStale(path);
      if ((await Array.fromAsync(Deno.readDir(path))).length === 0) await Deno.remove(path);
    } else if (!expected.has(path)) await Deno.remove(path);
  }
}

// Replaces the import map's `.wm` entries with the current modules, keeping the rest.
async function updateImportMap(modules: Record<string, string>): Promise<void> {
  const path = join(root, "deno.json");
  const config = JSON.parse(await Deno.readTextFile(path));
  const kept = Object.entries(config.imports ?? {}).filter(([key]) =>
    !(key.startsWith("./") && key.endsWith(".wm"))
  );
  config.imports = Object.fromEntries([...kept, ...Object.entries(modules)]);
  await writeIfChanged(path, JSON.stringify(config, null, 2) + "\n");
}
